# ══════════════════════════════════════════════════════════════
# 옛 도구는 걸음이 셋이었다 — 뽑기 → **배정** → 판정.  판정 방법이 그 걸음을
# 가리키며 쓰여 있었다 ("배정된 파일 안까지 열어…", "…배정됐는지").
#
# 통짜 설계에는 그 걸음이 없다.  모형이 짝을 짓고 값을 뽑고 판정까지 한 번에
# 한다.  그러니 모형에게 "배정된 파일" 이라 하면 **제가 방금 고른 파일**을
# 가리키는 말인지 알 수 없다.
#
# 비고 본의 「배정 0.86」 은 옛 점수다.  통짜에는 점수가 없고 확신만 있다.
import re as _re

_바꿈 = [
    (r"배정된 파일 \*\*안까지\*\* 열어", "네가 이 줄에 맺은 파일을 **끝까지 열어**"),
    (r"배정된 파일", "네가 맺은 파일"),
    (r"그 건에 배정된 문서가 있는지\.", "네가 이 줄에 맺은 파일이 있고, 그 안에 이 건의 증빙이 실제로 들어 있는지."),
    (r"그 행에 배정된 문서가 있는지\.", "네가 이 줄에 맺은 파일이 있고, 그 안에 이 건의 증빙이 실제로 들어 있는지."),
    (r"([^.]+?)\s*등이 배정됐는지\.", r"네가 맺은 파일 안에 \1 등이 실제로 들어 있는지."),
    (r"([^.]+?)\s*중 하나라도 배정됐는지\.", r"네가 맺은 파일 안에 \1 중 하나라도 실제로 들어 있는지."),
    (r"([^.]+?)\s*중 1종 이상 배정됐는지\.", r"네가 맺은 파일 안에 \1 중 하나 이상이 실제로 들어 있는지."),
]


def 낱말고침(글: str) -> str:
    t = str(글 or "")
    for a, b in _바꿈:
        t = _re.sub(a, b, t)
    return t


def 비고고침(글: str) -> str:
    """비고 본에서 옛 점수를 걷어낸다.  「배정 0.86 · 계획서 1건」 → 「계획서 1건」."""
    t = _re.sub(r"배정\s*[\d.]+\s*·\s*", "", str(글 or ""))
    t = _re.sub(r"배정\s*[\d.]+", "맺음 확인", t)
    return t.strip()


