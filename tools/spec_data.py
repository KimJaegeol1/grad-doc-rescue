# ⑤ 뽑을 값 이름 다듬기
# ══════════════════════════════════════════════════════════════
# 옛 설정의 「쓰는추출필드」 는 설명서에서 옮겨 온 **사람 말**이었다.
#
#     참여명단(저자) ↔ 별첨1        ← 이름이 아니라 문장이다
#     문서종류 ↔ 별첨1 학생분류
#     (배정 결과)
#
# 그대로 두면 모형에게 "「참여명단(저자) ↔ 별첨1」 을 뽑아라" 고 시키는 꼴이다.
# 별첨1 과 대조하라는 말은 이미 시트 지침과 판정 방법에 적혀 있으므로,
# 여기서는 **뽑을 값의 이름만** 남긴다.
def 값이름(raw: list) -> list:
    out = []
    for x in (raw or []):
        t = str(x).strip()
        t = t.split("↔")[0].strip()          # "A ↔ 별첨1" → "A"
        t = t.replace("(저자)", "").strip()   # "참여명단(저자)" → "참여명단"
        if not t or t.startswith("("):        # "(배정 결과)" 같은 것은 이름이 아니다
            continue
        if t == "인원":                       # 옛 이름 — 공통추출 이름으로 맞춘다
            t = "참여명단"
        if t not in out:
            out.append(t)
    return out


