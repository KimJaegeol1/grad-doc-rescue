def _c(ws, r, c, v, font=F_BODY, fill=None, align=A_L):
    cell = ws.cell(r, c, v)
    cell.font, cell.alignment, cell.border = font, align, BOX
    if fill:
        cell.fill = fill
    return cell


def _제목(ws, 글, 폭):
    ws.cell(1, 1, 글).font = F_TITLE
    ws.cell(1, 1).alignment = A_L
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=폭)
    ws.row_dimensions[1].height = 20


def _표(ws, 머리, 너비, 행=2):
    for i, h in enumerate(머리, 1):
        _c(ws, 행, i, h, F_HEAD, FILL_HEAD, A_C)
        ws.column_dimensions[gl(i)].width = 너비[i - 1]
    ws.row_dimensions[행].height = 31.5
    ws.freeze_panes = ws.cell(행 + 1, 3)


