def 항목장(wb, 시트, 항목들, 정):
    ws = wb.create_sheet(시트[:31])
    폴더 = (D.지침.get(시트) or {}).get("증빙폴더", "")
    _제목(ws, f"표1. {시트} — 검수 항목별 추출·판정 명세  "
              f"(총 {len(항목들)}항목"
              f"{' · 증빙 폴더 ' + 폴더 if 폴더 else ''})", len(머리))
    _표(ws, 머리, 너비)
    r = 3
    for c in 항목들:
        n = c["#"]
        who = D.주체(시트, n)
        새 = D.고쳐쓴판정.get((시트, n))
        정c = 정.get(n, {})
        fill = FILL_계산 if who == "계산" else (FILL_사람 if who == "사람" else None)

        판정 = dict(c.get("판정") or {})
        비고 = str(c.get("비고") or "")
        if 새:
            판정, 비고 = 새["판정"], 새["비고"]
        규칙 = D.규칙(시트, n, 정c.get("3단계 추출·판정 규칙", ""),
                      새["판정방법"] if 새 else c.get("판정방법", ""))
        값 = D.값이름(c.get("쓰는추출필드") or [])
        값 += [x for x in D.더할값.get((시트, n), []) if x not in 값]

        _c(ws, r, 1, n, F_BODY, fill, A_C)
        _c(ws, r, 2, c["검증열"], F_BODY, fill)
        _c(ws, r, 3, who, F_BODY, fill, A_C)
        _c(ws, r, 4, D.셈법.get((시트, n), "—"), F_BODY, fill)
        _c(ws, r, 5, D.대조축(시트, n, 정c.get("대조 축", "")), F_BODY, fill, A_C)
        _c(ws, r, 6, 정c.get("증빙 문서") or "—", F_BODY, fill)
        _c(ws, r, 7, " · ".join(값) or "—", F_BODY, fill)
        _c(ws, r, 8, D.엑셀열(시트, c.get("엑셀열") or ""), F_BODY, fill)
        _c(ws, r, 9, 규칙, F_BODY, fill)
        for j, k in enumerate(["O", "X", "확인 불가", "공란"], start=10):
            _c(ws, r, j, 판정.get(k) or "—", F_BODY, fill, A_C)
        _c(ws, r, 14, (f"[{c['검증열']}] {D.비고고침(비고)}" if 비고 else ""),
           F_BODY, fill)
        ws.row_dimensions[r].height = max(31.5, 12.5 * (1 + len(규칙) // 46))
        r += 1
    return ws


