def 봄(ok, 글, 덧=""):
    print(f"  {'✓' if ok else '❌'} {글}" + (f"   {덧}" if 덧 else ""))
    if not ok:
        탈.append(글)


def 칸(제목):
    print("\n" + "═" * 74)
    print(제목)
    print("═" * 74)


def 한줄(행, 파일, 확신="높음", 판정=None, 값=None):
    """모형이 낼 법한 줄 하나를 만든다.  판정은 줄 **안에 바로** 들어간다."""
    판정 = 판정 or {}
    한 = {"행": 행, "맺은파일": 파일, "맺은근거": "기업명·기간 일치",
          "확신": 확신, "값": 값 or {}, "메모": ""}
    for c in 모형것:
        v = 판정.get(c["검증열"])
        한[P._키(c["#"])] = {
            "검증열": c["검증열"],
            "판정": (v or {}).get("판정", "확인 불가"),
            "출처": (v or {}).get("출처", P.없음),
            "근거": (v or {}).get("근거", "p.1 표제"),
            "비고": (v or {}).get("비고", ""),
        }
    return 한


def 검사(답줄, 안맺힌=None):
    return A.검사(sp, 시트, {"줄": 답줄, "안맺힌파일": 안맺힌 or []}, 줄들, 파일들)


def 칸으로(답줄):
    """배열 대신 r3·r4 칸으로 담는다 — 진짜 규격이 오는 꼴."""
    return {P.행키(x["행"]): x for x in 답줄}


