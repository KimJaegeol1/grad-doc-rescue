    봄(목표 < P._한도(), "목표가 한도보다 낮다 — 규격·시스템 글 몫이 남는다",
       f"{목표:,} < {P._한도():,}")
    실제최대 = int(목표 / P.자당토큰 * 0.617)
    봄(실제최대 < P._한도(), "가장 나쁜 경우에도 한도 안이다",
       f"{실제최대:,}토큰 < {P._한도():,}")

    print("\n" + "═" * 74)
    if 탈:
        print(f"❌ {len(탈)}건이 어긋났다")
        for t in 탈:
            print(f"   · {t}")
        print("═" * 74)
        return 1
    print("✅ 어떤 크기가 와도 모형 한도 안에 든다 — 어림잡지 않고 재서 맞춘다")
    print("═" * 74)
    return 0


