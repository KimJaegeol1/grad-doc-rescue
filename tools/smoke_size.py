    표 = P.표들(파일들)

    def 같은데까지(a, b):
        n = 0
        for x, y in zip(a, b):
            if x != y:
                break
            n += 1
        return n

    첫 = P.build(sp, 시트0, 줄들, [], 파일들, 물을줄=[4, 5, 6, 7])
