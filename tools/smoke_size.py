    칸("⑦ 잰 값이 실제와 얼마나 다른가")
    print("  자당 토큰은 서울대 실측 두 개에서 나왔다.")
    print("    415,726자 → 256,377토큰  (0.617)")
    print("    479,082자 → 293,353토큰  (0.612)")
    print(f"  코드는 {P.자당토큰} 를 쓴다 — 실측보다 크게 잡아야 안전하다.\n")
