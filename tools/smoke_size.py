    os.environ["OPENAI_INPUT_LIMIT"] = "100000"
    try:
        작 = P.build(sp, list(sp.시트)[0], 줄들, [], 파일들, 물을줄=[4, 5])
    finally:
        os.environ.pop("OPENAI_INPUT_LIMIT", None)
    작목표 = min(P.토큰목표, int(100000 * 0.86))
    print(f"  한도 272,000 → 어림 {큰['잰것']['어림토큰']:,}토큰")
    print(f"  한도 100,000 → 어림 {작['잰것']['어림토큰']:,}토큰 (목표 {작목표:,})\n")
    봄(작["잰것"]["어림토큰"] <= 작목표, "좁은 한도에도 맞춘다")
    봄(작["잰것"]["어림토큰"] < 큰["잰것"]["어림토큰"], "한도가 좁으면 글도 짧아진다")

    # ── ⑥ 배치를 나눠도 앞부분이 안 달라진다 ────────────────
