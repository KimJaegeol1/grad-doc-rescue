# -*- coding: utf-8 -*-
"""
smoke_calc — 코드가 세는 15항목이 실물 표기를 견디는가

실제 서울대 엑셀에 적혀 있던 꼴을 그대로 넣어 본다.
    「2024.05.01-2024.08.31」  「24-06-03 ~ 24-06-16」  「25-02-10 ~ 25-02-14 (40H)」
    「25-08-25~29」            「2025학년도 1학기」      「979-11-XXXXX-X-X」

    python tools/smoke_calc.py
"""
from __future__ import annotations

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from core import calc as C, spec as S                             # noqa: E402

sp = S.load(HERE.parent / "docs" / "보조도구 검수기준.xlsx")
탈 = []


def 봄(ok, 글, 덧=""):
    print(f"  {'✓' if ok else '❌'} {글}" + (f"   {덧}" if 덧 else ""))
    if not ok:
        탈.append(글)


def 칸(제목):
    print("\n" + "═" * 74)
    print(제목)
    print("═" * 74)


def 항목(시트, n):
    return next(c for c in sp.항목(시트) if c["#"] == n)


def 재기(시트, n, 엑셀값, 증빙값=None, 앞선=None, 맺은파일=("01.pdf",)):
    """증빙값을 준다는 것은 **서류를 맺었다**는 뜻이라 맺은파일도 함께 준다.

    개요 제0조 ③ 장치는 닫히는 쪽이다 — 안 주면 확인 불가가 나온다.
    깜빡한 부름이 거짓 O 를 내는 것보다 확인 불가를 내는 편이 낫다.
    """
    return C.재기(항목(시트, n), 엑셀값, 증빙값 or {},
                  맺은파일=list(맺은파일), 앞선판정=앞선)


# ══════════════════════════════════════════════════════════════
칸("① 날짜 읽기 — 실물 표기 그대로")
# ══════════════════════════════════════════════════════════════
for 글, 바람 in [
    ("2024.05.01-2024.08.31", ["20240501", "20240831"]),
    ("24-06-03 ~ 24-06-16", ["20240603", "20240616"]),
    ("24년 06월 03일", ["20240603"]),
    ("25-02-10 ~ 25-02-14(40시간)", ["20250210", "20250214"]),
    ("25-08-25~29", ["20250825", "20250829"]),          # 뒤가 생략된 것
    ("2024년 5월", []),                                   # 날이 없다
]:
    got = C.날짜들(글)
    봄(got == 바람, f"「{글}」", " · ".join(got) or "(못 읽음)")

봄(C.날짜들("24-06-03")[0].startswith("2024"),
  "두 자리 연도를 편다 — 이것 하나 때문에 인턴십 22줄이 미배정된 적이 있다")


# ══════════════════════════════════════════════════════════════
칸("② 3개월 이상 여부  (③프로젝트 #5 — 전에는 비워 두던 칸)")
# ══════════════════════════════════════════════════════════════
for 글, 바람, 왜 in [
    ("2024.05.01-2024.08.31", "O", "4개월"),
    ("2024.05.08-2024.08.09", "O", "3개월"),
    ("2024.06.01-2024.07.31", "X", "2개월"),
    ("2024년 5월", "확인 불가", "날짜 둘로 못 읽음"),
    ("", "", "엑셀 공란"),
]:
    v, 비고, 근거 = 재기("③프로젝트", 5, {"기 간": 글})
    봄(v == 바람, f"「{글 or '(빈칸)'}」 → {v or '공란'}", f"{왜} · {비고 or 근거}")


# ══════════════════════════════════════════════════════════════
칸("③ 40시간 이상 여부  (⑤인턴십 #6)")
# ══════════════════════════════════════════════════════════════
for 글, 바람, 왜 in [
    ("80", "O", "80시간"),
    ("40", "O", "딱 40"),
    ("32시간", "X", "모자람"),
    ("(20H)+(20H)", "O", "나눠 적힌 것은 합산"),
    ("8H×5일", "확인 불가", "곱셈은 단정하지 않는다"),
    ("", "확인 불가", "증빙에 없음"),
]:
    v, 비고, 근거 = 재기("⑤인턴십", 6, {}, {"총시간": 글})
    봄(v == 바람, f"「{글 or '(빈칸)'}」 → {v}", f"{왜} · {비고 or 근거}")


# ══════════════════════════════════════════════════════════════
칸("④ 날짜 일치  (⑤인턴십 #9 — 엑셀 ↔ 증빙 표기가 다르다)")
# ══════════════════════════════════════════════════════════════
v, 비고, 근거 = 재기("⑤인턴십", 9, {"일시": "24-06-03 ~ 24-06-16"},
                     {"인턴기간_시작일": "24년 06월 03일",
                      "인턴기간_종료일": "24년 06월 16일"})
봄(v == "O", "엑셀 「24-06-03」 ↔ 증빙 「24년 06월 03일」 → O", 근거)

v, 비고, _ = 재기("⑤인턴십", 9, {"일시": "24-06-03 ~ 24-06-16"},
                  {"인턴기간_시작일": "24년 07월 01일",
                   "인턴기간_종료일": "24년 07월 19일"})
봄(v == "X", "정말 다르면 X", 비고)

v, 비고, _ = 재기("⑤인턴십", 9, {"일시": "24-06-03 ~ 24-06-16"}, {})
봄(v == "확인 불가", "증빙에서 못 뽑았으면 확인 불가 — X 가 아니다", 비고)

v, _b, _ = 재기("⑤인턴십", 9, {}, {"인턴기간_시작일": "24년 06월 03일"})
봄(v == "", "엑셀이 비었으면 공란")


# ══════════════════════════════════════════════════════════════
칸("⑤ 참여인원 일치  (⑤인턴십 #11 — 엑셀 ↔ 엑셀, 전에는 비워 두던 칸)")
# ══════════════════════════════════════════════════════════════
for 인원, 이름, 바람, 왜 in [
    ("3", "김재걸, 이수민, 박민수", "O", "3 = 3"),
    ("5", "김재걸, 이수민", "X", "5 ≠ 2"),
    ("18", "김은진", "X", "실물 — 인원 18인데 이름 1"),
    ("", "김재걸", "", "인원 칸이 빔"),
    ("셋", "김재걸", "확인 불가", "수로 못 읽음"),
]:
    v, 비고, 근거 = 재기("⑤인턴십", 11,
                        {"참여인원": 인원, "참여학생명": 이름})
    봄(v == 바람, f"인원 「{인원 or '(빈칸)'}」 · 이름 「{이름}」 → {v or '공란'}",
      f"{왜} · {비고 or 근거}")


# ══════════════════════════════════════════════════════════════
칸("⑥ 참여학생 수 일치  (③프로젝트 #9 — 엑셀 ↔ 증빙 명단)")
# ══════════════════════════════════════════════════════════════
v, 비고, 근거 = 재기("③프로젝트", 9, {"참여학생(명)": "3"},
                     {"참여명단": {"상태": "찾음",
                                   "이름": ["김재걸", "이수민", "박민수"]}})
봄(v == "O", "엑셀 3명 · 증빙 명단 3명 → O", 근거)

v, 비고, _ = 재기("③프로젝트", 9, {"참여학생(명)": "4"},
                  {"참여명단": {"상태": "찾음", "이름": ["김재걸", "이수민"]}})
봄(v == "X", "수가 다르면 X", 비고)

v, 비고, _ = 재기("③프로젝트", 9, {"참여학생(명)": "4"},
                  {"참여명단": {"상태": "명단없음", "이름": []}})
봄(v == "확인 불가", "★ 명단을 못 찾은 것은 0명이 아니다 — 확인 불가", 비고)

v, _b, _ = 재기("③프로젝트", 9, {"참여학생(명)": "4"},
                {"참여인원수": "참여학생 4명"})
봄(v == "O", "문서에 「참여학생 4명」 이라 적혀 있으면 그걸 쓴다")


# ══════════════════════════════════════════════════════════════
칸("⑦ ISBN")
# ══════════════════════════════════════════════════════════════
# 실제로 유효한 번호를 쓴다.  지어낸 번호로 시험하면 코드가 맞아도 틀린다
# (처음에 그렇게 해서 시험이 코드를 잘못 잡았다).
for 글, 바람, 왜 in [
    ("978-0-306-40615-7", "O", "13자리 · 검증숫자 7 맞음"),
    ("978-0-306-40615-8", "X", "끝자리만 틀린 것"),
    ("0-306-40615-2", "O", "10자리 · 나머지 0"),
    ("979-11-1234", "확인 불가", "9자리 — 자릿수가 아님"),
]:
    v, 비고, 근거 = 재기("⑥교재", 2, {"ISBN": 글})
    봄(v == 바람, f"「{글}」 → {v}", f"{왜} · {비고 or 근거}")

v, _b, _ = 재기("⑥교재", 6, {"ISBN": "978-0-306-40615-7"},
                {"ISBN": "9780306406157"})
봄(v == "O", "하이픈이 달라도 같은 번호면 O")

v, 비고, _ = 재기("⑥교재", 6, {"ISBN": "978-0-306-40615-7"},
                  {"ISBN": "978-0-13-110362-8"})
봄(v == "X", "다른 번호면 X", 비고)


# ══════════════════════════════════════════════════════════════
칸("⑧ 학기  (별첨3 #2)")
# ══════════════════════════════════════════════════════════════
for 엑, 증, 바람 in [
    ("2025-1", "2025학년도 1학기", "O"),
    ("25-1", "2025-1", "O"),
    ("2025-1", "2025학년도 2학기", "X"),
    ("2025-1", "봄학기", "확인 불가"),
]:
    v, 비고, 근거 = 재기("별첨3 개설교과", 2, {"학기": 엑}, {"학기": 증})
    봄(v == 바람, f"엑셀 「{엑}」 ↔ 증빙 「{증}」 → {v}", 비고 or 근거)


# ══════════════════════════════════════════════════════════════
칸("⑨ 앞선 항목이 X 면 물을 것이 없다  (④세미나 #7 ← #2)")
# ══════════════════════════════════════════════════════════════
v, 비고, _ = 재기("④세미나", 7, {"일시": "2024-05-03"},
                  {"일시_연월일": "2024년 5월 3일"}, 앞선={2: "확인 불가"})
봄(v == "", "#2 가 확인 불가면 #7 은 공란", 비고)

v, _b, _ = 재기("④세미나", 7, {"일시": "2024-05-03"},
                {"일시_연월일": "2024년 5월 3일"}, 앞선={2: "O"})
봄(v == "O", "#2 가 O 면 정상 판정")


# ══════════════════════════════════════════════════════════════
칸("⑩ 줄 하나를 통째로 — 모형 판정 옆에 계산 몫을 얹는다")
# ══════════════════════════════════════════════════════════════
줄 = {"맺은파일": ["01.pdf"],
      "값": {"총시간": "80", "인턴기간_시작일": "24년 06월 03일",
             "인턴기간_종료일": "24년 06월 16일",
             "참여명단": {"상태": "찾음", "이름": ["서혜빈"]}},
      "판정": {"계획서 제출여부": {"판정": "O", "근거": "p.1"}}}
엑셀값 = {"일시": "24-06-03 ~ 24-06-16", "시간(00H)": "40",
          "참여인원": "1", "참여학생명": "서혜빈", "기업명": "국립환경과학원"}
본 = C.채우기(sp, "⑤인턴십", 줄, 엑셀값)
계산것 = [c["검증열"] for c in sp.항목("⑤인턴십") if c["주체"] == "계산"]
봄(all(k in 본 for k in 계산것), f"계산 {len(계산것)}칸이 다 찼다")
봄(본["계획서 제출여부"]["판정"] == "O", "모형이 낸 판정은 그대로")
print()
for k in 계산것:
    v = 본[k]
    print(f"     {k:<22} {v['판정'] or '공란':<8} {v['비고'] or v['근거']}")
봄(본["시간 일치"]["판정"] == "X", "엑셀 40 ≠ 증빙 80 → X",
  본["시간 일치"]["비고"])
봄(all("코드가 셈" in 본[k]["근거"] for k in 계산것), "누가 판정했는지 근거에 남는다")


print()
print("═" * 74)
if 탈:
    print(f"❌ 어긋난 곳 {len(탈)}건")
    for x in 탈:
        print(f"   · {x}")
else:
    print("✅ 실물 표기를 견딘다 — 못 읽은 것은 X 가 아니라 확인 불가로 남긴다")
print("═" * 74)
raise SystemExit(1 if 탈 else 0)
