# ★ 정본과 코드가 **이름으로** 맺은 약속 — 여기 말고 다른 데 적지 않는다
# ══════════════════════════════════════════════════════════════
#   검수기준의 「추출 필드」 는 거의 다 코드가 뜻을 모른 채 모형에게 넘기고
#   모형이 채워 오는 값이다.  딱 둘만 코드가 **뜻을 안다.**
#
#       명단칸   사람 이름 목록이다.  수를 세고 상태(찾음·명단없음·글자깨짐)를
#                가려야 하므로 규격에서 혼자 다른 꼴(객체)을 쓴다
#       인원칸   증빙에 적힌 인원 표기.  명단을 못 뽑았을 때 비고에 남긴다
#
#   정본에서 이 이름을 바꾸면 코드가 못 알아보고 명단 대조가 **조용히** 죽는다.
#   이 도구에서 제일 나쁜 종류의 고장이다.  그래서 이름을 여기 한 곳에 두고,
#   정본이 비슷하지만 다른 이름을 쓰면 load 가 큰 소리로 알린다.
명단칸 = "참여명단"
인원칸 = "참여인원수"


def _약속확인(sp):
    """정본이 코드가 아는 이름을 그대로 쓰고 있는가."""
    쓰는값 = set()
    for 시 in sp.시트이름들():
        쓰는값 |= set(sp.뽑을값들(시))
    for 아는이름, 표시 in ((명단칸, "명단"), (인원칸, "인원")):
        if 아는이름 in 쓰는값:
            continue
        닮은 = [v for v in 쓰는값 if 표시 in v]
        if 닮은:
            sp.탈.append(
                f"코드는 「{아는이름}」 이라는 이름만 알아봅니다.  "
                f"정본에는 「{' · '.join(sorted(닮은))}」 (이)라고 적혀 있습니다 — "
                f"이대로면 {'명단 대조' if 아는이름 == 명단칸 else '인원 안내'}가 "
                f"동작하지 않습니다.  이름을 「{아는이름}」 로 맞춰 주세요")


