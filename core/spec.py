def load(path) -> Spec:
    """검수기준 엑셀 → Spec.  파일이 없으면 여기서 멈춘다."""
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(
            f"검수기준 엑셀을 찾지 못했습니다 — {p}\n"
            f"이 파일이 규칙 정본입니다.  프로그램 옆에 있어야 합니다.")
    sp = Spec(p)
    wb = load_workbook(p, data_only=True)
    try:
        # ★ 낱말장을 **먼저** 읽는다.  시트장의 「엑셀 대조 열」 을 펴는 데 쓴다.
        for 장 in wb.sheetnames:
            if 장.strip() == 낱말장:
                sp.낱말 = _낱말장(sp, wb[장])
        for 장 in wb.sheetnames:
            ws = wb[장]
            if 장.strip() in (공통장, 낱말장):
                if 장.strip() == 공통장:
                    sp.공통규칙 = _장통째로(ws)
                    sp.공통뽑을값 = _공통값(sp.공통규칙)
                continue
            elif 장.strip() in 곁장:
                continue                       # 종합표·추출 필드는 이 장들에서 뽑아 만든 것
            else:
                _시트장(sp, 장.strip(), ws)
    finally:
        wb.close()

    if not sp.시트:
        sp.탈.append("시트 장을 하나도 찾지 못했습니다 — "
                     "2행 첫 칸이 「#」 인 표가 있어야 합니다")
    if not sp.공통규칙:
        sp.탈.append(f"'{공통장}' 장을 찾지 못했습니다 — 공통 규칙이 프롬프트에서 빠집니다")
    _약속확인(sp)
    _겹침확인(sp)
    return sp


def _공통값(글: str) -> list:
    """공통 규칙 장의 「공통으로 뽑을 값: A · B · C」 한 줄을 찾아 읽는다.

    표가 아니라 글줄로 둔 것은 사람이 읽을 자리와 코드가 읽을 자리를 따로
    만들지 않기 위해서다.  사람이 보는 그 줄이 곧 코드가 읽는 줄이다.
    """
    m = re.search(r"공통으로\s*뽑을\s*값\s*[::]\s*(.+)", 글)
    return _나눔(m.group(1)) if m else []


def _장통째로(ws) -> str:
    """장의 글을 위에서 아래로 이어 붙인다.  병합된 칸이라 A열만 보면 된다."""
    줄 = []
    for r in range(1, (ws.max_row or 0) + 1):
        v = _글(ws.cell(r, 1).value)
        줄.append(v)
    while 줄 and not 줄[-1]:
        줄.pop()
    return "\n".join(줄)


def _시트장(sp: Spec, 이름: str, ws):
    """항목표만 있는 장.  1행 = 표 제목, 2행 = 머리글, 3행부터 항목.

    머리글 줄을 **자리로 못박지 않는다** — 사람이 위에 줄을 끼워 넣을 수 있다.
    첫 칸이 「#」 인 줄을 찾는다.
    """
    머리행 = 0
    for r in range(1, min((ws.max_row or 0), 12) + 1):
        if _글(ws.cell(r, 1).value) == "#":
            머리행 = r
            break
    if not 머리행:
        return                                  # 시트 장이 아니다 — 조용히 지나간다

    폴더 = ""
    m = re.search(r"(별첨\s*[\d,\s]+)", _글(ws.cell(1, 1).value))
    if m:
        폴더 = m.group(1).strip()

    sp.시트[이름] = {"증빙폴더": 폴더, "지침": {},
                     "항목": _표읽기(sp, 이름, ws, 머리행)}


def _표읽기(sp: Spec, 시트: str, ws, 머리행: int) -> list:
    실제 = [_글(ws.cell(머리행, c).value) for c in range(1, len(머리) + 1)]
    for i, 바람 in enumerate(머리):
        got = 실제[i] if i < len(실제) else ""
        if _nk(바람) not in _nk(got):
            sp.탈.append(f"{시트} — {i + 1}번째 머리글이 「{got or '(빈칸)'}」 입니다.  "
                         f"「{바람}」 이어야 합니다")

    # ── 줄 읽기 ──────────────────────────────────────────
    항목, 본번호, 본이름 = [], set(), set()
    for r in range(머리행 + 1, (ws.max_row or 0) + 1):
        첫 = _글(ws.cell(r, 1).value)
        if not 첫:
            continue
        if not 첫.isdigit():
            break                                # 표가 끝났다 (아래는 범례)
        n = int(첫)
        검증열 = _글(ws.cell(r, 2).value)
        주체 = _글(ws.cell(r, 3).value)
        방법 = _글(ws.cell(r, 9).value)

        어디 = f"{시트} #{n}"
        if not 검증열:
            sp.탈.append(f"{어디} — 검증열이 비어 있습니다.  이 줄은 건너뜁니다")
            continue
        if n in 본번호:
            sp.탈.append(f"{어디} — 번호가 겹칩니다.  뒤엣것은 건너뜁니다")
            continue
        if _nk(검증열) in 본이름:
            sp.탈.append(f"{어디} 「{검증열}」 — 검증열 이름이 겹칩니다.  "
                         f"엑셀에서 어느 칸을 채울지 정할 수 없습니다")
        if 주체 not in 주체들:
            sp.탈.append(f"{어디} 「{검증열}」 — 판정 주체가 「{주체 or '(빈칸)'}」 입니다.  "
                         f"{' · '.join(주체들)} 중 하나여야 합니다.  모형으로 봅니다")
            주체 = "모형"
        if 주체 == "계산" and not _셈법(ws.cell(r, 4).value).get("셈"):
            sp.탈.append(f"{어디} 「{검증열}」 — 판정 주체가 '계산' 인데 셈법이 "
                         f"「{_글(ws.cell(r, 4).value) or '(빈칸)'}」 입니다.  "
                         f"코드가 어떤 셈인지 알 수 없어 확인 불가로 둡니다")
        if 주체 != "사람" and not 방법:
            sp.탈.append(f"{어디} 「{검증열}」 — 판정 방법이 비어 있습니다.  "
                         f"모형에게 무엇을 보라고 할지 알 수 없습니다")

        본번호.add(n)
        본이름.add(_nk(검증열))
        항목.append({
            "#": n,
            "검증열": 검증열,
            "주체": 주체,
            "셈법": _셈법(ws.cell(r, 4).value),
            "대조축": _글(ws.cell(r, 5).value),
            "증빙문서": _글(ws.cell(r, 6).value),
            "뽑을값": _나눔(ws.cell(r, 7).value),
            "엑셀열": _펴기(sp, _나눔(ws.cell(r, 8).value)),
            "판정방법": 방법,
            "판정": {k: _글(ws.cell(r, 10 + i).value)
                     for i, k in enumerate(판정값)},
            "비고본": _글(ws.cell(r, 14).value),
        })
    if not 항목:
        sp.탈.append(f"{시트} — 항목을 하나도 읽지 못했습니다")
    return 항목


