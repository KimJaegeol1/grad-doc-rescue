# -*- coding: utf-8 -*-
"""
core.spec — 검수기준 엑셀을 읽는다.  **정본이 코드로 들어오는 유일한 문.**
================================================================
이 파일 말고는 아무도 검수기준을 모른다.  프롬프트도, 계산도, 보고서도
여기서 읽은 것만 본다.  그래서 여기가 틀리면 전부가 틀린다.

읽는 규약
────────
    0. 읽는 법        사람만 읽는다.  코드는 안 본다
    0. 공통 규칙      **프롬프트에 통째로 실린다**
    0. 엑셀 열 찾기    사람이 읽는 것 + 코드가 어떻게 찾는지 적어 둔 것.
                     프롬프트에는 안 실린다 (모형이 할 일이 아니다)
    그 밖의 장        시트 하나.  위 = 시트 지침, 아래 = 항목표

시트 장의 짜임
    ▌ 시트 지침 …          ← 이 줄부터 지침이 시작된다
       이름 줄
       내용 줄              ← **이름 줄 다음 줄이 그 내용이다.**  짝으로 읽는다
       …
    ▌ 항목표 …             ← 이 줄부터 표가 시작된다
       # | 검증열 | 판정 주체 | … (머리글 11칸)
       1 | …                 ← 첫 칸이 숫자인 줄만 항목이다

왜 이렇게 무르게 읽나
────────────────────
사람이 고치는 파일이다.  줄을 더하고 지우고 색을 바꾼다.  그래서
**자리(몇 행 몇 열)로 찾지 않고 표지(▌ · 머리글 이름)로 찾는다.**

왜 이렇게 시끄럽게 구나
──────────────────────
조용히 넘어가면 그 항목이 통째로 사라진 채 검사가 끝난다.  사람은 O 도 X 도
아닌 빈 칸을 보고 "판정을 안 했나 보다" 한다 — 규칙이 안 읽힌 줄은 모른다.
그래서 어긋난 곳을 모아 두었다가 한 번에 다 알려 준다 (`Spec.탈`).
"""

from __future__ import annotations

import re
from pathlib import Path

from openpyxl import load_workbook

# ── 장 이름 ──────────────────────────────────────────────────
#   짜임은 「[3단계] 파일 개봉 검수정의서 v1.1」 을 따랐다.
#   시트 지침 블록은 없앴다 — 그 내용은 개요의 조문(제5~8조)으로 옮겼다.
공통장 = "개요"           # ★ 프롬프트에 통째로 실린다
낱말장 = "열 낱말"         # ★ 대표 이름 ↔ 학교마다 달리 쓰는 이름 — 한 군데서 관리
곁장 = ("종합표", "추출 필드", "개정 이력")   # 사람이 보는 것.  코드는 안 읽는다

머리 = ["#", "검수 항목", "판정주체", "셈법", "대조 축", "증빙 문서",
        "추출 필드", "엑셀 대조 열", "판정 규칙", "O", "X", "확인 불가", "공란",
        "비고 문구"]
주체들 = ("모형", "계산", "사람")
판정값 = ("O", "X", "확인 불가", "공란")

_없음 = {"", "—", "-", "–", "없음", "none", "n/a"}


def _글(v) -> str:
    return "" if v is None else str(v).strip()


def _나눔(v) -> list:
    """「A · B · C」 → [A, B, C].  없음 표시는 빈 목록."""
    s = _글(v)
    if s.lower() in _없음:
        return []
    return [x.strip() for x in re.split(r"·|\|", s) if x.strip()]


def _낱말장(sp, ws) -> dict:
    """「열 낱말」 장을 읽는다.  {아무 이름(정규화): [대표, 별칭…]}.

    ★ 왜 따로 한 장을 두나
    ──────────────────────
    별칭을 시트마다 적었더니 ③프로젝트는 「참여기관(기업) · 참여기관 · 기업명」
    셋인데 ⑤인턴십은 「기업명」 하나였다.  같은 뜻인데 시트마다 달랐다.
    그러면 코드가 아무리 범용이어도 **정본의 어휘가 사실상 인터페이스**가 되고,
    학교가 「참여기관」 이라 적은 순간 그 항목이 통째로 빠진다.

    그래서 대표 이름 하나에 학교들이 쓰는 이름을 모아 **한 군데서** 적는다.
    시트의 「엑셀 대조 열」 칸은 대표 이름만 적어도 되고, 여기서 펴 준다.
    시트에만 있는 이름을 더 적어도 된다 — 그것도 같이 쓰인다.

    표 꼴 (머리글 줄은 첫 칸이 「대표 이름」 인 줄)
        대표 이름 | 학교들이 달리 쓰는 이름
        기업명    | 참여기관 · 참여기관(기업) · 기관명 · 업체명 · 실습기관

    ★ 겹치는 낱말은 여기서 안 따진다
    ──────────────────────────────
    「일시」 는 ④세미나에선 개최일이고 ⑦논문에선 게재일이다.  같은 낱말이
    여러 대표 이름에 들어가는 것은 **정상**이다.  위험한 것은 **한 시트 안에서**
    두 항목이 같은 낱말을 노려 같은 열을 집는 경우뿐이다.  그래서 겹침은
    시트를 다 읽은 뒤 _겹침확인 이 시트마다 본다.

    찾을 때 쓰는 열쇠는 **대표 이름뿐**이다.  별칭으로는 못 편다 — 일부러다.
    「참여학생(명)」 은 괄호를 떼면 「참여학생명」 과 같아지는데, 하나는 사람
    **수**고 하나는 **이름**이다.  별칭으로도 펴게 두면 시트에 적어 둔 낱말이
    엉뚱한 줄로 펴져 수 칸이 이름 칸을 집는다.  대표 이름만 편다.
    """
    머리 = 0
    for r in range(1, min(ws.max_row or 1, 10) + 1):
        if _nk(ws.cell(r, 1).value) == _nk("대표 이름"):
            머리 = r
            break
    if not 머리:
        sp.탈.append(f"'{낱말장}' 장에서 머리글 줄을 찾지 못했습니다 — "
                     f"첫 칸이 「대표 이름」 인 줄이 있어야 합니다")
        return {}
    지도: dict = {}
    줄들 = []
    for r in range(머리 + 1, (ws.max_row or 0) + 1):
        대표 = _글(ws.cell(r, 1).value)
        if not 대표:
            continue
        모두 = [대표] + [x for x in _나눔(ws.cell(r, 2).value) if x]
        본, 줄 = set(), []
        for x in 모두:                          # 차례를 지키며 겹치는 것만 뺀다
            if _nk(x) in 본:
                continue
            본.add(_nk(x))
            줄.append(x)
        if _nk(대표) in 지도:
            sp.탈.append(f"'{낱말장}' — 대표 이름 「{대표}」 가 두 줄에 있습니다.  "
                         f"뒤엣것은 건너뜁니다")
            continue
        지도[_nk(대표)] = 줄
        줄들.append(줄)
    return 지도


def _겹침확인(sp):
    """한 시트 안에서 두 항목이 같은 열 이름을 노리는가.

    ★ 그러면 둘이 같은 열을 집는다.  ⑤인턴십의 「참여학생명」(이름) 과
      「참여인원」(수) 이 같은 낱말을 나눠 가지면, 이름 칸을 수로 세거나
      그 반대가 된다 — 조용히 틀린 판정이 나온다.
    """
    for 시 in sp.시트이름들():
        임자: dict = {}
        for c in sp.항목(시):
            L = c.get("엑셀열") or []
            if not L:
                continue
            보임 = L[0]
            for x in L:
                앞 = 임자.get(_nk(x))
                if 앞 and 앞 != 보임:
                    sp.탈.append(
                        f"{시} — 「{x}」 를 「{앞}」 과 「{보임}」 이 함께 노립니다.  "
                        f"둘이 같은 열을 집게 됩니다 — '{낱말장}' 에서 한쪽을 빼 주세요")
                임자.setdefault(_nk(x), 보임)


def _펴기(sp, 이름들: list) -> list:
    """시트에 적힌 열 이름을 낱말장으로 편다.  차례는 적힌 것이 앞선다.

    시트가 「기업명」 하나만 적어도 낱말장의 「참여기관 · 기관명 …」 이 따라온다.
    대표 이름이 아닌 것은 **그대로 둔다** — 그 시트에만 있는 이름이라는 뜻이다.
    """
    본, 줄 = set(), []
    for 이름 in 이름들 or []:
        for x in [이름] + (sp.낱말.get(_nk(이름)) or []):
            if _nk(x) in 본:
                continue
            본.add(_nk(x))
            줄.append(x)
    return 줄


셈이름 = ("날짜", "수", "이름개수", "기간", "값", "ISBN유효", "ISBN같음", "학기")


def _셈법(v) -> dict:
    """「기간 ≥ 3개월」 · 「날짜 · 앞선#2」 · 「이름개수 · 이름칸=참여학생명」 을 읽는다.

    글이 아니라 **칸**으로 둔 이유 — 판정 방법 글에도 "3개월 이상" 이라고
    적혀 있지만, 코드가 그 글을 읽어 셈을 고르게 하면 사람이 문구를 다듬는
    순간 셈이 바뀐다.  사람이 고치는 자리와 코드가 읽는 자리를 갈라 둔다.
    """
    s = _글(v)
    if not s or s in _없음:
        return {}
    민 = s.replace(" ", "")
    out: dict = {}
    for 이름 in 셈이름:
        if 민.startswith(이름) or f"·{이름}" in 민:
            out["셈"] = 이름
            break
    m = re.search(r"[≥>=]+\s*(\d+(?:\.\d+)?)\s*([^\s·]*)", s)
    if m:
        out["임계"] = float(m.group(1))
        out["단위"] = m.group(2)
    m = re.search(r"앞선\s*#?(\d+)", s)
    if m:
        out["앞선"] = int(m.group(1))
    m = re.search(r"이름칸\s*=\s*([^·]+)", s)
    if m:
        out["이름칸"] = m.group(1).strip()
    out["글"] = s
    return out


def _nk(s) -> str:
    """이름 견줄 때 쓰는 꼴.  머리글이 조금 흔들려도 알아본다.

    ★ 괄호는 **지우지 않는다** (core.book 과 같은 규약).  「참여학생(명)」 은
      사람 수, 「참여학생명」 은 이름이다 — 괄호가 뜻을 나른다.
    """
    return re.sub(r"[\s·,\[\]{}~\-_.:;/\\「」'\"]+", "", str(s or "")).lower()


