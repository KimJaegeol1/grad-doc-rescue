class Spec:
    """읽어 낸 검수기준.

    공통규칙   글 (프롬프트에 통째로 실린다)
    시트       {시트이름: {"증빙폴더", "지침": {이름: 글}, "항목": [...]}}
    탈         어긋난 곳 [글]  — 비어 있어야 정상이다
    """

    def __init__(self, path):
        self.경로 = Path(path)
        self.공통규칙 = ""
        self.공통뽑을값: list = []      # 항목표에 없어도 전 시트에서 뽑는 값
        self.낱말: dict = {}            # 열 이름 별칭 — 한 군데서 관리한다
        self.열찾기 = ""
        self.시트: dict = {}
        self.탈: list = []

    # ── 겉면 ──────────────────────────────────────────────
    def 시트이름들(self) -> list:
        return list(self.시트)

    def 항목(self, 시트: str) -> list:
        return (self.시트.get(시트) or {}).get("항목", [])

    def 지침(self, 시트: str) -> dict:
        return (self.시트.get(시트) or {}).get("지침", {})

    def 주체별(self, 시트: str, who: str) -> list:
        return [c for c in self.항목(시트) if c["주체"] == who]

    def 검증열들(self, 시트: str) -> list:
        return [c["검증열"] for c in self.항목(시트)]

    def 뽑을값들(self, 시트: str) -> list:
        """그 시트에서 증빙에서 뽑아야 하는 값 이름 — 겹치는 것은 한 번만.

        항목표에 적힌 것 + 공통으로 뽑을 값.  공통 셋은 어느 검증열에도
        안 걸리지만 추출 내역에 남겨야 하므로 여기서 얹는다.
        """
        out = list(self.공통뽑을값)
        for c in self.항목(시트):
            for f in c["뽑을값"]:
                if f not in out:
                    out.append(f)
        return out

    def 요약(self) -> list:
        out = [(f"검수기준 {self.경로.name} — 시트 {len(self.시트)}장 · "
                f"항목 {sum(len(v['항목']) for v in self.시트.values())}개", "head")]
        for s, v in self.시트.items():
            n = {w: len([c for c in v["항목"] if c["주체"] == w]) for w in 주체들}
            out.append((f"  {s:<14} {len(v['항목']):>2}항목  "
                        f"(모형 {n['모형']} · 계산 {n['계산']} · 사람 {n['사람']})",
                        "ok"))
        if self.탈:
            out.append((f"어긋난 곳 {len(self.탈)}건 — 그 항목은 검사에서 빠집니다", "warn"))
            for x in self.탈[:12]:
                out.append(("  · " + x, "warn"))
        return out


