def 표들(파일들) -> list:
    """파일마다 표를 붙인다.  `file_01` · `file_02` …

    ★ 모형이 파일을 가리키는 **유일한** 길이다.  이름은 못 쓰게 한다.
      순서는 부르는 쪽이 준 차례 그대로다 — prompt 와 schema 가 같은 표를
      쓰려면 둘 다 이 함수를 거쳐야 한다.
    """
    n = len(파일들 or [])
    폭 = max(2, len(str(n)))
    return [f"file_{i:0{폭}d}" for i in range(1, n + 1)]


def 이름들(파일들) -> list:
    """(이름, 글) 든 것도, 이름만 든 것도 이름만 뽑아 준다."""
    out = []
    for f in (파일들 or []):
        out.append(f[0] if isinstance(f, (list, tuple)) else f)
    return [str(x) for x in out]


