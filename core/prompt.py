꼬리몫 = 0.4          # 몫이 넘칠 때 **뒤쪽**에 줄 비율
꼬리최소 = 2000       # 몫이 이보다 작으면 나누지 않는다 (둘 다 쓸모없어진다)


def _머리꼬리(글: str, 칸수: int) -> tuple:
    """몫에 맞춰 글을 자른다.  반환 (실을 글, 잘라 낸 가운데 글자 수).

    ★ 앞에서만 자르면 **뒤에 있는 것을 통째로 못 본다**
    ────────────────────────────────────────────
    실제로 서울대 ⑦논문 39편에서 「사사 제시 여부」 가 O 1 · 확인 불가 38 이
    나왔다.  사사(Acknowledgements)는 논문 **끝**에 있는데 앞 10,256자만
    실었기 때문이다.  모형이 스스로 이렇게 적었다 —

        "Acknowledgements 단락이 PDF 후반부에 있을 가능성 있으나
         제공된 앞부분만 확인"

    ⑧학술발표도 같다.  초록집 하나에 발표 여럿이 실리는데(15-18_…pdf),
    앞부분만 보면 뒤에 실린 발표는 못 찾는다 — 37~50줄이 통째로 못 맺었다.

    뒤에 있는 것들
        사사·감사의 글 · 게재 정보(권·호·쪽) · 참고문헌 · 초록집의 뒷 발표

    앞에 있는 것들
        표제 · 저자 · 학술지 · 날짜 · 초록  ← **어느 줄인지 가리는 데** 쓴다

    그래서 앞을 더 주되(6) 뒤도 반드시 준다(4).  같은 글자 수로 훨씬 많이 본다.
    몫 안에 드는 파일은 **손대지 않는다** — 통째로 그대로 실린다.
    """
    글 = str(글 or "")
    if len(글) <= 칸수:
        return 글, 0
    if 칸수 < 꼬리최소:                      # 너무 작으면 나눠 봐야 둘 다 못 쓴다
        return 글[:칸수], len(글) - 칸수
    꼬리 = int(칸수 * 꼬리몫)
    머리 = 칸수 - 꼬리
    가운데 = len(글) - 칸수
    return (글[:머리]
            + f"\n\n…가운데 {가운데:,}자 잘림…\n\n"
            + 글[-꼬리:], 가운데)


