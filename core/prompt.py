def _키(n: int) -> str:
    return f"v{n}"


def 행키(n) -> str:
    """엑셀 행 번호 → 답의 칸 이름.  4 → 'r4'."""
    return f"r{int(n)}"


def 줄풀기(답: dict, 물을줄: list) -> tuple:
    """`{"줄": {"r3": {...}}}` 를 [{"행": 3, ...}] 로 되돌린다.

    반환 (줄 목록, 빠진 행 목록)

    ★ 행 번호는 **칸 이름에서** 가져온다.  모형이 안에 적은 '행' 은 안 믿는다.
      규격이 칸 이름은 못 바꾸게 하지만 안의 숫자는 틀릴 수 있다.
    """
    본 = (답 or {}).get("줄")
    if isinstance(본, list):                      # 옛 꼴(배열)도 받아 준다
        있 = {x.get("행") for x in 본}
        return list(본), [n for n in (물을줄 or []) if n not in 있]
    본 = 본 or {}
    나온, 빠짐 = [], []
    for n in (물을줄 or []):
        v = 본.get(행키(n))
        if not isinstance(v, dict):
            빠짐.append(n)
            continue
        한 = dict(v)
        한["행"] = int(n)
        나온.append(한)
    return 나온, 빠짐


def schema(sp, 시트: str, 파일들=(), 물을줄=()) -> dict:
    """모형이 낼 꼴을 못박는다 (Structured Outputs, strict).

    ★ 판정을 **배열이 아니라 칸**으로 둔다.  배열이면 빈 배열도 규격에 맞아
      모형이 아무 답도 안 낸 채 통과한다.  칸마다 required 를 걸면 못 그런다.

    ★ 줄도 마찬가지다.  `r3` · `r4` … 칸으로 두고 전부 required 로 건다.
      배열로 두었더니 22줄 중 6줄만 답하고 닫았다 (온전한 JSON 이었다).

    ★ 파일은 **표의 enum** 으로 둔다.  자유 글자로 두었더니 모형이 이름을
      기억으로 다시 써서 21줄이 전부 버려졌다.  enum 이면 지어낼 자리가 없다.

    ※ uniqueItems 는 strict 가 안 받는다.  같은 표를 두 번 적어 와도 규격은
      통과하니, 겹치는 것은 core.ask.검사 가 코드로 추린다.
    """
    항목 = sp.항목(시트)
    모형것 = [c for c in 항목 if c["주체"] == "모형"]
    뽑을값 = sp.뽑을값들(시트)
    표 = 표들(파일들)
    # 파일이 하나도 없으면 enum 을 비울 수 없다 (규격이 안 받는다).
    # 그런 판은 core.flow 가 먼저 멈추므로 여기 오지 않지만, 시험용으로 막아 둔다.
    파일표 = {"type": "string", "enum": 표 or [없음]}

    # ── 출처 enum 은 커지면 접는다 ────────────────────────
    #   strict 는 스키마 하나에 든 enum 값을 통틀어 1,000개까지만 받는다.
    #   줄을 칸으로 박으면 줄마다 스키마가 통째로 되풀이되므로 금세 는다.
    #
    #   ★ 어림잡지 않는다.  **다 짓고 나서 센다.**
    #     예전엔 공식으로 어림잡았는데, 줄마다 되풀이되는 것을 빠뜨렸다 —
    #     판정값(4)·확신(4)·명단상태(3) 가 줄 수만큼 늘어나는 것을 안 셌다.
    #
    #         ④세미나 · 파일 15개 · 8줄
    #             어림    903   →  950 아래라 판단해 enum 을 그대로 뒀다
    #             실제  1,151   →  API 가 400 으로 튕겼다 (한도 1,000)
    #
    #     빠진 248 = 4×6칸×8줄 + 4×8줄 + 3×8줄.  공식을 다듬으면 또 틀린다.
    #     그래서 **한 번 지어 보고 세어** 넘치면 「출처」 만 자유 글자로 되돌린다.
    #     맺은파일 enum 이 본 자물쇠이고 출처는 그것을 거드는 것이라 이 차례가
    #     맞다.  자유 글자로 와도 core.ask.검사 가 있는 표인지 보고 버린다.
    출처표 = {"type": "string", "enum": (표 or []) + [없음]}
    if _enum수(_짓기(모형것, 뽑을값, 파일표, 출처표, 물을줄)) > 한도:
        출처표 = {"type": "string"}
    return _짓기(모형것, 뽑을값, 파일표, 출처표, 물을줄)


한도 = 1000            # strict 가 스키마 하나에 받는 enum 값 수


def 맞는묶음(sp, 시트: str, 파일들, 바라는: int) -> int:
    """규격이 한도 안에 드는 **가장 큰** 묶음 크기.  최소 1.

    ★ 「출처」 를 접어도 안 되는 판이 있다.  파일이 아주 많으면 맺은파일
      enum 만으로도 줄 수 × 파일 수가 되어 한도를 넘는다 (⑤인턴십 · 파일
      80개 · 8줄 = 1,032).

      그때 맺은파일 enum 을 풀면 안 된다 — 그게 「파일 이름을 지어내지
      않는다」(제0조 ①) 를 지키는 본 자물쇠다.  대신 **한 번에 묻는 줄을
      줄인다.**  호출이 늘 뿐, 앞부분은 캐시에 걸려 값은 크게 안 오른다.
    """
    for n in range(max(1, int(바라는 or 8)), 0, -1):
        if _enum수(schema(sp, 시트, 파일들, list(range(3, 3 + n)))) <= 한도:
            return n
    return 1


def _enum수(o) -> int:
    """지어 놓은 규격에 든 enum 값을 **실제로** 센다.  어림잡지 않는다."""
    n = 0
    if isinstance(o, dict):
        if isinstance(o.get("enum"), list):
            n += len(o["enum"])
        for v in o.values():
            n += _enum수(v)
    elif isinstance(o, list):
        for v in o:
            n += _enum수(v)
    return n


def _짓기(모형것, 뽑을값, 파일표, 출처표, 물을줄) -> dict:
    """규격을 짓는다.  출처표만 갈아 끼워 두 번 부른다 (재어 보고 → 진짜로)."""
    값칸 = {}
    for f in 뽑을값:
        if f == _S.명단칸:
            값칸[f] = {
                "type": "object",
                "properties": {
                    "상태": {"type": "string", "enum": 명단상태},
                    "이름": {"type": "array", "items": {"type": "string"}},
                },
                "required": ["상태", "이름"],
                "additionalProperties": False,
            }
        elif f == "문서종류":
            값칸[f] = {"type": "array", "items": {"type": "string"}}
        else:
            값칸[f] = {"type": "string"}

    판정칸 = {_키(c["#"]): {
        "type": "object",
        "properties": {
            "검증열": {"type": "string"},          # 무엇에 답한 것인지 되뇌게 한다
            "판정": {"type": "string", "enum": 판정값},
            "출처": dict(출처표),                  # ★ 어느 서류를 보고 낸 판정인가
            "근거": {"type": "string"},
            "비고": {"type": "string"},
        },
        "required": ["검증열", "판정", "출처", "근거", "비고"],
        "additionalProperties": False,
    } for c in 모형것}

    줄칸 = {
        "행": {"type": "integer"},
        "맺은파일": {"type": "array", "items": dict(파일표)},
        "맺은근거": {"type": "string"},
        "확신": {"type": "string", "enum": ["높음", "보통", "낮음", "못맺음"]},
        "값": {"type": "object", "properties": 값칸,
               "required": list(값칸), "additionalProperties": False},
        "메모": {"type": "string"},
    }
    필수 = ["행", "맺은파일", "맺은근거", "확신", "값", "메모"]
    # ★ 판정을 줄 **안에 바로** 둔다 (예전엔 "판정" 아래 한 겹 더 있었다).
    #   줄을 칸으로 박으면서 겹이 하나 늘었는데, 규격이 받는 겹 수에 한도가
    #   있다.  여기서 한 겹을 덜어 예전과 같은 깊이로 되돌린다.
    줄칸.update(판정칸)
    필수 += list(판정칸)

    한줄꼴 = {"type": "object", "properties": 줄칸,
              "required": 필수, "additionalProperties": False}

    # ★ 줄을 칸으로 박는다.  물을줄이 없으면(시험용) 옛 배열 꼴로 둔다.
    if 물을줄:
        줄꼴 = {"type": "object",
                "properties": {행키(n): 한줄꼴 for n in 물을줄},
                "required": [행키(n) for n in 물을줄],
                "additionalProperties": False}
    else:
        줄꼴 = {"type": "array", "items": 한줄꼴}

    return {
        "type": "object",
        "properties": {
            "줄": 줄꼴,
            "안맺힌파일": {"type": "array", "items": {
                "type": "object",
                "properties": {"파일": dict(파일표), "왜": {"type": "string"}},
                "required": ["파일", "왜"], "additionalProperties": False}},
        },
        "required": ["줄", "안맺힌파일"],
        "additionalProperties": False,
    }


def 판정풀기(sp, 시트: str, 한줄: dict) -> dict:
    """모형의 v1·v2… 답을 검증열 이름으로 되돌린다.

    반환 {검증열: {"판정", "출처", "근거", "비고"}}
         출처는 아직 표(file_01) 그대로다.  실제 이름으로 되돌리는 것은
         core.ask.검사 의 몫이다 — 파일 목록을 아는 쪽이 거기다.
    """
    한줄 = 한줄 or {}
    옛 = 한줄.get("판정") or {}          # 예전 꼴 — "판정" 아래 한 겹 더 있었다
    out = {}
    for c in sp.항목(시트):
        if c["주체"] != "모형":
            continue
        v = 한줄.get(_키(c["#"])) or 옛.get(_키(c["#"])) or {}
        if str(v.get("판정") or "").strip():
            출 = str(v.get("출처") or "").strip()
            out[c["검증열"]] = {
                "판정": v["판정"] if v["판정"] != "공란" else "",
                "출처": "" if 출 == 없음 else 출,
                "근거": str(v.get("근거") or "")[:200],
                "비고": str(v.get("비고") or "")[:200],
            }
    return out
