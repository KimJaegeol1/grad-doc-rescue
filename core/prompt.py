def _몫나누기(길이들: list, 통틀어: int, 파일당: int) -> list:
    """파일마다 몇 자씩 실을지 정한다.  **공평하게 나눈다.**

    ★ 먼저 온 파일부터 채우면 뒤엣것이 0자가 된다.
      실제로 서울대 인턴십 18개(합 463,710자)에서 두 파일이 **0자**로,
      한 파일이 58자로 실렸다.  모형은 그 파일을 아예 못 본 것이고,
      그러면 그 줄은 "증빙이 없다" 가 되어 버린다.

    그래서 물채우기로 나눈다 — 낮은 것부터 고르게 채우고, 작은 파일이 제 몫을
    다 안 쓰면 그 나머지를 큰 파일들에게 다시 나눠 준다.  **아무도 0 이 아니다**
    (통틀어가 파일 수보다 적지 않은 한).

    ★ 파일당 상한이 **제 몫보다 낮으면 안 된다**
      학교가 서류를 한 파일로 묶어 내는 일이 있다.  그때 파일이 하나뿐인데도
      60,000자에서 잘려, 남은 27만 자 자리를 비워 둔 채 "뒤는 못 봤다" 가
      되었다.  상한은 한 파일이 남을 독차지하지 못하게 두는 것이지, 독차지할
      상대가 없을 때까지 묶어 둘 까닭은 없다.  그래서 **고르게 나눈 몫보다는
      낮지 않게** 한다 (파일이 많으면 예전과 똑같다).
    """
    n = len(길이들)
    if not n:
        return []
    파일당 = max(파일당, 통틀어 // n)
    상한 = [min(L, 파일당) for L in 길이들]
    if sum(상한) <= 통틀어:
        return 상한
    몫 = [0] * n
    남 = 통틀어
    for k, i in enumerate(sorted(range(n), key=lambda i: 상한[i])):
        고른몫 = 남 // (n - k)
        몫[i] = min(상한[i], 고른몫)
        남 -= 몫[i]
    return 몫


