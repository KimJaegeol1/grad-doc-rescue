def _꼬리자리(파일들) -> int:
    """맨 끝의 **배치마다 달라지는 토막**에 미리 비워 둘 자리 (글자 수).

    ★ 왜 미리 비워 두나 — 안 그러면 캐시가 통째로 깨진다
    ──────────────────────────────────────────────
    처음엔 배치마다 글을 지어 보고 재서 예산을 줄였다.  그런데 맨 끝의
    「이번에 답할 줄」·「앞선 배치가 가져간 파일」 이 배치마다 수백 자씩
    달라서 **맞춰 낸 예산도 배치마다 몇 자씩 달라졌다.**  예산이 1자만
    달라도 증빙 18개가 전부 다른 자리에서 잘린다 — 앞부분이 24.5%밖에
    안 같았다.

    앞부분은 23만 토큰이다.  캐시가 깨지면 배치 세 개에 값이 세 배로 든다.

    그래서 예산은 **파일 목록만 보고** 정한다 (배치와 무관하다).  끝 토막의
    몫은 여기서 미리 떼어 둔다.  가장 큰 것이 임자 목록이라 파일 수에 비례한다.
    """
    return 6000 + len(파일들 or []) * 160


_예산기억 = {}


def 글자예산(sp, 시트: str, 줄들: list, 명단: list, 파일들: list, *,
             파일당=60000) -> int:
    """증빙 글을 몇 자까지 실을지 정한다.  **배치와 무관한 값이다.**

    지어 보고 재서 넘치면 줄여 다시 짓는다.  숫자를 코드에 박아 두면
    시트마다·학교마다 달라 언젠가 튕긴다 — 실제로 50만 자로 두었다가
    293,353토큰이 되어 272,000 한도를 넘겼다.
    """
    열쇠 = (id(sp), 시트, len(줄들), len(명단), 파일당, _한도(),
            tuple(len(str(g or "")) for _n, g in 파일들))
    if 열쇠 in _예산기억:
        return _예산기억[열쇠]
    목표 = min(토큰목표, int(_한도() * 0.86)) - int(_꼬리자리(파일들) * 자당토큰)
    예산 = int(목표 / 자당토큰)                    # 넉넉히 잡고 시작한다
    첫줄 = [줄들[0]["행"]] if 줄들 else None       # 끝 토막을 가장 짧게 두고 잰다
    for _ in range(6):
        잰 = _짓기한장(sp, 시트, 줄들, 명단, 파일들, 물을줄=첫줄,
                       파일당=파일당, 통틀어=예산)["잰것"]["어림토큰"]
        if 잰 <= 목표:
            break
        줄일것 = int(예산 * 목표 / max(잰, 1)) - 2000
        if 줄일것 >= 예산 or 줄일것 < 20000:
            break
        예산 = 줄일것
    _예산기억[열쇠] = 예산
    return 예산


def build(sp, 시트: str, 줄들: list, 명단: list, 파일들: list, *,
          물을줄=None, 임자=None, 되짚기="", 파일당=60000, 통틀어=0) -> dict:
    """글 한 장을 만든다.  **모형 한도에 맞을 때까지 재서 줄인다.**

    예산은 `글자예산` 이 파일 목록만 보고 한 번 정한다.  배치가 달라도 같은
    값이라, 증빙 글이 배치마다 한 글자도 안 달라진다 (캐시).

    줄들    [{"행": 4, "값": {열이름: 글}}]        **시트의 줄 전부** (본보기로 다 싣는다)
    명단    [{"이름": "김재걸", "학생분류": "재직자"}]
    파일들  [(파일이름, 글)]                        engines.read 가 뽑은 글
    물을줄  [4, 5, 6 …]                          이번에 답을 받을 줄.  None 이면 전부
    임자    {표: [행…]}                          앞선 배치가 이미 가져간 파일
    되짚기  "…"                                  다시 부르는 까닭 (있으면 맨 끝에 붙는다)

    반환 {"system", "user", "잰것": {...}, "자름": [...]}
    """
    예산 = 통틀어 or 글자예산(sp, 시트, 줄들, 명단, 파일들, 파일당=파일당)
    한장 = _짓기한장(sp, 시트, 줄들, 명단, 파일들,
                     물을줄=물을줄, 임자=임자, 되짚기=되짚기,
                     파일당=파일당, 통틀어=예산)

    # ── 안전판 ────────────────────────────────────────────
    #    끝 토막이 떼어 둔 자리보다 크면(되짚기가 아주 길 때) **이 배치만** 줄인다.
    #    캐시가 깨지는 것보다 튕기지 않는 것이 먼저다.
    상한 = int(_한도() * 0.93)
    for _ in range(4):
        if 한장["잰것"]["어림토큰"] <= 상한 or 통틀어:
            break
        예산 = int(예산 * 상한 / max(한장["잰것"]["어림토큰"], 1)) - 4000
        if 예산 < 20000:
            break
        한장 = _짓기한장(sp, 시트, 줄들, 명단, 파일들,
                         물을줄=물을줄, 임자=임자, 되짚기=되짚기,
                         파일당=파일당, 통틀어=예산)
    한장["잰것"]["글자예산"] = 예산
    return 한장


